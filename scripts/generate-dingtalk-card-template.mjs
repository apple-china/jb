function visit(nodes) {
  for (const node of nodes ?? []) {
    if (node.componentName === 'BaseText' && node.props?.maxLine) {
      node.props.maxLine.valueType = 'fixed';
      node.props.maxLine.value = 1;
    }
    visit(node.children);
  }
}
visit(root.children);

